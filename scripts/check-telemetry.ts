import { launchBrowser } from "./chromium.ts";
import { mkdirSync } from "node:fs";

mkdirSync("output", { recursive: true });
const browser = await launchBrowser();
const errors: string[] = [];
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
page.on("pageerror", e => errors.push(e.message));
let saves = 0;
page.on("request", req => { if (req.url().includes("/api/me/home") && req.method() === "PUT") saves++; });
try {
  // Browser-only installation fixture: exercising a 3 kWp household must not alter the database.
  await page.route("**/api/me/home", async route => {
    const response = await route.fetch();
    const data = await response.json();
    if (data.home) { data.home.installedPv = true; data.home.installedKwp = 3; }
    await route.fulfill({ response, json: data });
  });
  await page.addInitScript(() => sessionStorage.setItem("malas:landing-seen", "1"));
  await page.goto("http://localhost:3000/?cahaya=day");
  if (await page.getByRole("button", {name:"Lewati intro"}).isVisible()) await page.getByRole("button", {name:"Lewati intro"}).click();
  await page.locator(".dashboard-header").getByRole("button", { name: "Masuk", exact: true }).click();
  await page.getByRole("button", { name: "Masuk sebagai warga demo" }).click();
  const sensor = page.getByRole("region", { name: "Sensor simulasi gedung" });
  await sensor.waitFor();
  await sensor.locator(".iot-experiments > summary").click();
  await sensor.getByText("Rincian sensor dan laporan", {exact:true}).click();
  await sensor.getByRole("button", { name: "Uji cerah", exact: true }).click();
  const seq = await sensor.getAttribute("data-sequence");
  await page.waitForTimeout(2300);
  if (await sensor.getAttribute("data-sequence") === seq) throw new Error("Virtual packet clock stopped");
  const clear = Number(await sensor.getAttribute("data-solar"));
  await sensor.getByRole("button", { name: "Uji hujan", exact: true }).click();
  await page.waitForFunction(() => Boolean((window as any).__malasMap.getRain()));
  const rain = Number(await sensor.getAttribute("data-solar"));
  if (!(clear > rain && rain > 0)) throw new Error("Rain does not reduce simulated PV");
  await sensor.getByRole("button", { name: "Uji malam", exact: true }).click();
  await page.waitForFunction(() => (window as any).__malasMap.getConfigProperty("basemap", "lightPreset") === "night");
  if (Number(await sensor.getAttribute("data-solar")) !== 0 || Number(await sensor.getAttribute("data-import")) <= 0) throw new Error("Night balance is wrong");
  await page.locator('.energy-beacon[data-level="high"]').waitFor();
  if (!(await sensor.locator(".energy-impact").first().innerText()).includes("kg CO₂/jam")) throw new Error("Home CO2 comparison is missing");
  await sensor.getByRole("button", { name: "Uji koneksi terputus" }).click();
  const frozen = await sensor.getAttribute("data-sequence");
  await page.waitForTimeout(2300);
  if (await sensor.getAttribute("data-sequence") !== frozen) throw new Error("Disconnected device invents new packets");
  const pausedEffect = await page.locator(".energy-beacon__halo > i").first().evaluate(el => getComputedStyle(el).animationPlayState);
  if (pausedEffect !== "paused") throw new Error("Offline effect keeps emitting animated packets");
  await sensor.getByRole("button", { name: "Sambungkan kembali" }).click();
  await sensor.getByRole("button", { name: "Uji cerah", exact: true }).click();
  await sensor.getByRole("spinbutton", { name: "Kapasitas uji PLTS" }).fill("4");
  await page.locator('.energy-beacon[data-level="clean"]').waitFor();
  const download = page.waitForEvent("download");
  await sensor.getByRole("button", { name: "Unduh laporan simulasi" }).click();
  const report = await download;
  if (!(report.suggestedFilename().endsWith(".csv"))) throw new Error("Simulation report did not download");
  await report.saveAs("output/iot-simulation-report.csv");
  await sensor.getByRole("button", { name: "Lihat karakter 3D" }).click();
  await page.waitForFunction(() => { const map = (window as any).__malasMap; return map.getSource("illustrative-people")?._data.features.length > 0 && map.getZoom() > 19.8; });
  await page.waitForTimeout(1500);
  const firstPeople = await page.evaluate(() => JSON.stringify((window as any).__malasMap.getSource("illustrative-people")._data));
  await page.waitForTimeout(400);
  const movingPeople = await page.evaluate(first => JSON.stringify((window as any).__malasMap.getSource("illustrative-people")._data) !== first, firstPeople);
  if (!movingPeople) throw new Error("Map characters do not walk");
  await page.screenshot({ path: "output/iot-characters-3d.png" });
  await page.locator(".character img").evaluateAll(images => images.forEach(image => (image as HTMLImageElement).loading = "eager"));
  await page.waitForFunction(() => [...document.querySelectorAll<HTMLImageElement>(".character img")].every(image => image.complete && image.naturalWidth > 0));
  await sensor.locator(".iot-monitor__header").scrollIntoViewIfNeeded();
  await page.screenshot({ path: "output/iot-home-live.png" });
  await page.getByRole("button", { name: "Manfaat untuk saya", exact:true }).click();
  await page.getByRole("button", { name: "Lihat pilihan panel di atap" }).click();
  await page.getByRole("region", {name:"Simulasi pemasangan panel surya"}).waitFor();
  if (await page.locator(".building-panel").count()) throw new Error("Resident left their fixed home");
  await page.screenshot({ path: "output/iot-home-lab.png" });
  await page.locator(".citizen-header").getByRole("button", {name:"Keluar",exact:true}).click();
  await page.locator(".dashboard-header").getByRole("button", {name:"Masuk",exact:true}).click();
  await page.getByRole("button", {name:"Masuk sebagai pemda demo"}).click();
  await page.locator(".dashboard-nav").getByRole("button", { name: /^Digital twin/ }).click();
  await page.getByText("Sensor simulasi aktif", { exact: true }).waitFor();
  await page.getByRole("button", { name: "Putar 24 jam" }).waitFor();
  const firstClock = await page.locator(".twin-live-status").textContent();
  await page.waitForTimeout(2300);
  if (await page.locator(".twin-live-status").textContent() === firstClock) throw new Error("Regional twin is not live");
  await page.waitForFunction(() => (window as any).__malasMap.getZoom() < 8);
  await page.screenshot({ path: "output/iot-twin-live.png" });
  await page.getByRole("button", { name: "Putar 24 jam" }).click();
  await page.getByRole("button", { name: "Jeda", exact: true }).waitFor();
  await page.waitForTimeout(900);
  await page.getByRole("button", { name: "Jeda", exact: true }).click();
  await page.getByRole("button", { name: "Simulasi langsung", exact: true }).click();
  await page.getByText("Sensor simulasi aktif", { exact: true }).waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator(".dashboard-header").getByRole("button", {name:"Keluar",exact:true}).click();
  await page.locator(".dashboard-header").getByRole("button", {name:"Masuk",exact:true}).click();
  await page.getByRole("button", {name:"Masuk sebagai warga demo"}).click();
  await sensor.waitFor();
  await page.waitForTimeout(1000);
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
  if (overflow) throw new Error("Sensor dashboard overflows mobile viewport");
  await page.screenshot({ path: "output/iot-home-mobile.png" });
  if (saves || errors.length) throw new Error(JSON.stringify({ saves, errors }));
  console.log(JSON.stringify({ packetMs: 2000, clearKw: clear, rainyKw: rain, offline: "frozen", fixedHomeLab: true, regionalLive: true, charactersWalk: movingPeople, lucideIcons: await page.locator("svg.lucide").count(), writesToHome: saves, errors }));
} catch (error) {
  await page.screenshot({ path: "output/iot-browser-failure.png" });
  console.log(await page.locator(".building-panel").textContent().catch(() => "No building panel"));
  console.log(await page.evaluate(() => { const map = (window as any).__malasMap; return { center: map?.getCenter(), zoom: map?.getZoom(), styleLoaded: map?.isStyleLoaded(), loaded: map?.loaded() }; }));
  throw error;
} finally { await browser.close(); }
